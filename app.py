def conectar_bd():
    return psycopg2.connect(st.secrets["DATABASE_URL"], connect_timeout=10)


def inicializar_bd():
    conn = conectar_bd()
    try:
        with conn.cursor() as cursor:
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS public.registros (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    fecha TIMESTAMPTZ DEFAULT NOW(),
                    codigo_paciente TEXT UNIQUE NOT NULL,
                    edad INTEGER,
                    bll DOUBLE PRECISION,
                    hb_medida DOUBLE PRECISION,
                    hb_ajustada DOUBLE PRECISION,
                    residencia INTEGER,
                    cercania INTEGER,
                    antecedentes INTEGER,
                    indice_r_porcentaje DOUBLE PRECISION,
                    nivel_riesgo TEXT,
                    altitud_evaluacion INTEGER DEFAULT 1120,
                    es_torreon INTEGER DEFAULT 1
                )
            """)
        conn.commit()
    finally:
        conn.close()


def consultar_registros(columnas="*"):
    consultas = {
        "*": "SELECT * FROM public.registros",
        "detalle": """SELECT id, fecha, codigo_paciente, edad, bll, hb_medida,
                     hb_ajustada, altitud_evaluacion, residencia, cercania,
                     antecedentes, indice_r_porcentaje, nivel_riesgo
                     FROM public.registros ORDER BY id DESC"""
    }
    conn = conectar_bd()
    try:
        with conn.cursor() as cursor:
            cursor.execute(consultas[columnas])
            nombres = [col[0] for col in cursor.description]
            filas = cursor.fetchall()
        return pd.DataFrame(filas, columns=nombres)
    finally:
        conn.close()


